import 'dart:io';
import 'package:path/path.dart' as path;

import 'logger.dart';

/// A utility class for managing file and directory paths used in the distribution process.
///
/// The `Files` class provides static references to commonly used files and directories,
/// such as Android and iOS distribution directories, changelogs, and metadata paths.
/// This class cannot be instantiated and serves as a centralized location for
/// all file path constants used throughout the distribution process.
class Files {
  /// Private constructor to prevent instantiation.
  ///
  /// The `Files` class is intended to be used only with its static members.
  Files._();

  /// The file containing Android changelogs for distribution
  ///
  /// Path: `distribution/android/output/changelogs.log`
  static final File androidChangeLogs = File(
    path.join("distribution", "android", "output", "changelogs.log"),
  );

  /// The Fastlane JSON configuration file for automated deployment
  ///
  /// Path: `distribution/google-key.json`
  static final File fastlaneJson = File(
    path.join("distribution", "google-key.json"),
  );

  /// The root directory for Android distribution files
  ///
  /// Path: `distribution/android`
  static final Directory androidDistributionDir = Directory(
    path.join("distribution", "android"),
  );

  /// The directory containing Android app bundles generated by the build process
  ///
  /// Path: `build/app/outputs/bundle`
  static final Directory androidOutputAppbundles = Directory(
    path.join("build", "app", "outputs", "bundle"),
  );

  /// The directory containing Android APKs generated by the build process
  ///
  /// Path: `build/app/outputs/flutter-apk`
  static final Directory androidOutputApks = Directory(
    path.join("build", "app", "outputs", "flutter-apk"),
  );

  /// The output directory for Android distribution files
  ///
  /// Path: `distribution/android/output`
  static final Directory androidDistributionOutputDir = Directory(
    path.join(androidDistributionDir.path, "output"),
  );

  /// The metadata directory for Android distribution files
  ///
  /// Path: `distribution/android/metadata`
  static final Directory androidDistributionMetadataDir = Directory(
    path.join(androidDistributionDir.path, "metadata"),
  );

  /// The root directory for custom distribution files
  ///
  /// Path: `distribution/custom`
  static final Directory customDir = Directory(
    path.join("distribution", "custom"),
  );

  /// The metadata directory for custom distribution files
  ///
  /// Path: `distribution/custom/metadata`
  static final Directory customOutputMetadataDir = Directory(
    path.join(customDir.path, "metadata"),
  );

  /// The output directory for custom distribution files
  ///
  /// Path: `distribution/custom/output`
  static final Directory customOutputDir = Directory(
    path.join(customDir.path, "output"),
  );

  /// The root directory for iOS distribution files
  ///
  /// Path: `distribution/ios`
  static final Directory iosDistributionDir = Directory(
    path.join("distribution", "ios"),
  );

  /// The directory containing iOS IPA files generated by the build process
  ///
  /// Path: `build/ios/ipa`
  static final Directory iosOutputIPA = Directory(
    path.join("build", "ios", "ipa"),
  );

  /// The output directory for iOS distribution files
  ///
  /// Path: `distribution/ios/output`
  static final Directory iosDistributionOutputDir = Directory(
    path.join(iosDistributionDir.path, "output"),
  );

  /// The metadata directory for iOS distribution files
  ///
  /// Path: `distribution/ios/metadata`
  static final Directory iosDistributionMetadataDir = Directory(
    path.join(iosDistributionDir.path, "metadata"),
  );

  /// Copies files from source directory to target directory with optional filtering.
  ///
  /// This method recursively copies files from the source directory to the target directory.
  /// It can filter files by file type and supports different build modes.
  ///
  /// Parameters:
  /// - `source` - The source directory path to copy from
  /// - `target` - The target directory path to copy to
  /// - `fileType` - List of file extensions to filter by (without dots, e.g., `['apk', 'aab']`)
  /// - `mode` - Build mode filter (defaults to "release")
  ///
  /// Returns the path of the first copied file.
  ///
  /// Throws an Exception if:
  /// - No files are found in the source directory
  /// - No files match the specified file type filter
  static Future<String?> copyFiles(
    String source,
    String target, {
    List<String> fileType = const [],
    String mode = "release",
    String? flavor,
  }) async {
    final sourceDir = Directory(source);
    if (!sourceDir.existsSync()) {
      throw Exception("No files found in ${sourceDir.path}");
    }

    final targetDir = Directory(target);
    if (!targetDir.existsSync()) {
      await targetDir.create(recursive: true);
    }

    final entities = await sourceDir.list(recursive: true).toList();
    final extensions = fileType.map((value) => value.toLowerCase()).toSet();

    final candidates = <_FileCandidate>[];
    for (final entity in entities) {
      if (entity is! File) continue;
      if (extensions.isNotEmpty) {
        final extension = path.extension(entity.path).toLowerCase();
        if (!extensions.contains(extension.replaceFirst('.', ''))) {
          continue;
        }
      }

      final sourcePath = entity.path.toLowerCase();
      final score = _artifactScore(sourcePath, mode: mode, flavor: flavor);
      final modifiedAt = entity.lastModifiedSync();
      candidates.add(
        _FileCandidate(path: entity.path, score: score, modifiedAt: modifiedAt),
      );
    }

    if (candidates.isEmpty) {
      throw Exception(
        "Does not contain any files with the specified type: $fileType",
      );
    }

    candidates.sort((a, b) {
      final scoreComparison = b.score.compareTo(a.score);
      if (scoreComparison != 0) return scoreComparison;
      return b.modifiedAt.compareTo(a.modifiedAt);
    });

    final logger = ColorizeLogger();

    // Scoring is relative, so a directory holding nothing but `app-debug.apk`
    // makes that file the best candidate and ships it as the release. A build
    // mode that is named in the path but is not the one asked for is a
    // different artifact, not a lower-ranked one.
    if (mode.isNotEmpty) {
      final wrongMode = candidates
          .where((candidate) => _namesAnotherMode(candidate.path, mode))
          .toList();
      if (wrongMode.length == candidates.length) {
        throw Exception(
          "No $mode artifact found in ${sourceDir.path}. "
          "The closest match is ${path.basename(candidates.first.path)}, which "
          "is not a $mode build — run the build for this mode first.",
        );
      }
      for (final dropped in wrongMode) {
        logger.logDebug(
          "Ignoring ${path.basename(dropped.path)}: it is not a $mode build",
        );
      }
      candidates.removeWhere(wrongMode.contains);
    }

    // Keep only the best matching tier. A `--split-per-abi` build legitimately
    // produces several artifacts, and those all score identically - but a stale
    // `app-debug.apk` from an earlier run scores lower, and copying it into the
    // release output directory is how a debug binary ends up in a release.
    final bestScore = candidates.first.score;
    final selected =
        candidates.where((candidate) => candidate.score == bestScore).toList();

    for (final dropped in candidates.where((c) => c.score != bestScore)) {
      logger.logDebug(
        "Ignoring ${path.basename(dropped.path)}: does not match "
        "mode '$mode'${flavor == null ? '' : " / flavor '$flavor'"}",
      );
    }

    final output = <String>[];
    final keptNames = <String>{};
    for (final candidate in selected) {
      final fileName = path.basename(candidate.path);
      final targetPath = path.join(target, fileName);
      keptNames.add(fileName);
      output.add(targetPath);

      // Pointing `output:` at the directory the build already writes to makes
      // source and target the same file. Deleting the target first and then
      // copying "from" it destroyed the artifact outright, and the caller only
      // reported a failed copy.
      if (_isSameFile(candidate.path, targetPath)) {
        logger.logDebug("$fileName is already in place; leaving it alone");
        continue;
      }

      if (File(targetPath).existsSync()) {
        await File(targetPath).delete();
      }
      await File(candidate.path).copy(targetPath);
    }

    await _pruneStaleArtifacts(targetDir, extensions, keptNames, logger);

    return output.first;
  }

  /// Removes artifacts left in [targetDir] by a previous, different build.
  ///
  /// Publishers scan the output directory rather than a single file, so a
  /// leftover binary there is a binary that can still be uploaded. Only files
  /// matching [extensions] are considered, which keeps the blast radius inside
  /// the artifacts this tool put there in the first place.
  /// Whether [artifactPath] is labelled with a build mode other than [mode].
  ///
  /// Flutter names its outputs `app-debug.apk`, `app-profile.apk`,
  /// `app-release.apk` and puts them under `.../debug/`, `.../release/`. A path
  /// carrying one of the other modes is a different build, not a worse match
  /// for this one — shipping it would put a debug binary in a store listing.
  static bool _namesAnotherMode(String artifactPath, String mode) {
    const modes = {'debug', 'profile', 'release'};
    final wanted = mode.toLowerCase();
    if (!modes.contains(wanted)) return false;

    final normalized = artifactPath.toLowerCase();
    bool marks(String candidate) => [
          '/$candidate/',
          '-$candidate.',
          '-$candidate-',
          '_$candidate.',
        ].any(normalized.contains);

    if (marks(wanted)) return false;
    return modes.where((m) => m != wanted).any(marks);
  }

  /// Whether two paths refer to the same file on disk.
  ///
  /// Compared after resolving symlinks and normalising, because `output:` is
  /// written by hand: `distribution/../build/app/outputs` and an absolute path
  /// to the same directory are the same place, and neither string matches.
  static bool _isSameFile(String a, String b) {
    if (path.equals(path.normalize(a), path.normalize(b))) return true;
    try {
      final left = File(a);
      final right = File(b);
      if (!left.existsSync() || !right.existsSync()) return false;
      return path.equals(
        left.resolveSymbolicLinksSync(),
        right.resolveSymbolicLinksSync(),
      );
    } on FileSystemException {
      return false;
    }
  }

  static Future<void> _pruneStaleArtifacts(
    Directory targetDir,
    Set<String> extensions,
    Set<String> keptNames,
    ColorizeLogger logger,
  ) async {
    if (extensions.isEmpty) return;

    for (final entity in targetDir.listSync()) {
      if (entity is! File) continue;
      final fileName = path.basename(entity.path);
      if (keptNames.contains(fileName)) continue;

      final extension =
          path.extension(entity.path).replaceFirst('.', '').toLowerCase();
      if (!extensions.contains(extension)) continue;

      await entity.delete();
      logger
          .logDebug("Removed stale artifact $fileName from ${targetDir.path}");
    }
  }

  static int _artifactScore(
    String sourcePath, {
    required String mode,
    String? flavor,
  }) {
    var score = 0;
    final normalizedPath = sourcePath.toLowerCase();
    final normalizedMode = mode.toLowerCase();
    final normalizedFlavor = flavor?.toLowerCase();

    if (normalizedFlavor != null && normalizedFlavor.isNotEmpty) {
      if (normalizedPath.contains('/$normalizedFlavor/')) score += 50;
      if (normalizedPath.contains('-$normalizedFlavor-')) score += 50;
      if (normalizedPath.contains(normalizedFlavor)) score += 20;
    }

    if (normalizedMode.isNotEmpty) {
      if (normalizedPath.contains('/$normalizedMode/')) score += 40;
      if (normalizedPath.contains('-$normalizedMode-')) score += 40;
      if (normalizedPath.contains('-$normalizedMode.')) score += 40;
      if (normalizedPath.contains(normalizedMode)) score += 15;
    }

    if (normalizedPath.contains('/outputs/')) score += 10;
    if (normalizedPath.contains('/bundle/')) score += 8;
    if (normalizedPath.contains('/flutter-apk/')) score += 8;
    if (normalizedPath.contains('/apk/')) score += 5;

    return score;
  }
}

class _FileCandidate {
  final String path;
  final int score;
  final DateTime modifiedAt;

  const _FileCandidate({
    required this.path,
    required this.score,
    required this.modifiedAt,
  });
}

/// Expands shell style patterns in a configured path.
///
/// `distribution/android/output/*.apk` is the natural way to write "whatever
/// the build produced", and every other tool in a release pipeline accepts it.
/// Supported: `*` (anything but a separator), `?` (one character), `[abc]` (a
/// set), and `**` (any number of directories).
class Glob {
  const Glob._();

  /// Characters that make a path a pattern rather than a literal.
  static final RegExp _magic = RegExp(r'[*?\[]');

  /// Whether [pattern] needs expanding at all.
  ///
  /// A path with no magic is left completely alone, so a directory that happens
  /// to be named oddly still behaves the way it always did.
  static bool hasMagic(String pattern) => _magic.hasMatch(pattern);

  /// Every existing file matching [pattern], newest first.
  ///
  /// Returns an empty list when nothing matches; the caller decides whether
  /// that is an error, because a dry run legitimately has nothing to match yet.
  static List<File> expand(String pattern, {Directory? from}) {
    final normalized = pattern.replaceAll('\\', '/');
    final segments = normalized.split('/');

    // Everything before the first magic segment is a real directory to start
    // from; listing the whole tree from the working directory would be absurd
    // for a pattern that named one folder.
    final fixed = <String>[];
    var index = 0;
    while (index < segments.length && !hasMagic(segments[index])) {
      fixed.add(segments[index]);
      index++;
    }
    if (index == segments.length) {
      // No magic after all — resolve it as the plain path it is, still
      // relative to `from` so the two branches agree.
      final literal = from == null ? pattern : path.join(from.path, pattern);
      final file = File(literal);
      return file.existsSync() ? [file] : const [];
    }

    final rootPath = fixed.isEmpty
        ? (from?.path ?? '.')
        : (from == null
            ? fixed.join(Platform.pathSeparator)
            : path.join(from.path, fixed.join(Platform.pathSeparator)));

    final root = Directory(rootPath);
    if (!root.existsSync()) return const [];

    final remainder = segments.sublist(index).join('/');
    final matcher = _toRegExp(remainder);
    final recursive = remainder.contains('**') || remainder.contains('/');

    final matches = <File>[];
    for (final entity in root.listSync(recursive: recursive)) {
      if (entity is! File) continue;
      final relative =
          path.relative(entity.path, from: root.path).replaceAll('\\', '/');
      if (matcher.hasMatch(relative)) matches.add(entity);
    }

    matches.sort(
      (a, b) => b.lastModifiedSync().compareTo(a.lastModifiedSync()),
    );
    return matches;
  }

  /// Compiles a glob into an anchored regular expression.
  static RegExp _toRegExp(String pattern) {
    final buffer = StringBuffer('^');
    for (var i = 0; i < pattern.length; i++) {
      final char = pattern[i];
      if (char == '*') {
        // `**` crosses directories; a single `*` stops at the separator, which
        // is what stops `out/*.apk` from reaching into `out/nested/`.
        if (i + 1 < pattern.length && pattern[i + 1] == '*') {
          buffer.write('.*');
          i++;
          if (i + 1 < pattern.length && pattern[i + 1] == '/') i++;
        } else {
          buffer.write('[^/]*');
        }
        continue;
      }
      if (char == '?') {
        buffer.write('[^/]');
        continue;
      }
      if (char == '[') {
        final close = pattern.indexOf(']', i + 1);
        if (close != -1) {
          buffer.write(pattern.substring(i, close + 1));
          i = close;
          continue;
        }
      }
      buffer.write(RegExp.escape(char));
    }
    buffer.write(r'$');
    return RegExp(buffer.toString());
  }
}
